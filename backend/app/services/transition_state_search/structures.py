from __future__ import annotations

from ase import Atoms

from app.contracts.jobs import (
    Atom,
    AtomicStructure,
    BondChangeAssessment,
    CalculationProgress,
    ReactionCoordinate,
)
from uma_workflows.transition_states.workflow import WorkflowProgress
from uma_workflows.transition_states import assess_bond_changes


def max_force(forces) -> float:
    """Return the largest Cartesian force norm in eV/A."""
    import numpy as np

    vectors = np.asarray(forces, dtype=float).reshape(-1, 3)
    return float(np.linalg.norm(vectors, axis=1).max(initial=0.0))


def to_atoms(structure: AtomicStructure) -> Atoms:
    atoms = Atoms(
        symbols=[atom.symbol for atom in structure.atoms],
        positions=[atom.position for atom in structure.atoms],
        pbc=False,
    )
    atoms.info.update({"charge": structure.charge, "spin": structure.spin})
    return atoms


def structure_from_positions(
    template: AtomicStructure,
    positions,
    *,
    name: str,
) -> AtomicStructure:
    return AtomicStructure(
        atoms=[
            Atom(
                symbol=atom.symbol,
                position=tuple(float(value) for value in position),
            )
            for atom, position in zip(template.atoms, positions, strict=True)
        ],
        charge=template.charge,
        spin=template.spin,
        name=name,
        comment="Generated by correlated FB-ENM and Direct MaxFlux",
        source_format="xyz",
    )


def structure_from_atoms(
    template: AtomicStructure,
    atoms: Atoms,
    *,
    name: str,
) -> AtomicStructure:
    return structure_from_positions(template, atoms.positions, name=name)


def progress_to_schema(
    template: AtomicStructure,
    event: WorkflowProgress,
) -> CalculationProgress:
    return CalculationProgress(
        step=event.step,
        max_steps=event.max_steps,
        energy_ev=event.energy_ev,
        max_force_ev_per_a=event.max_force_ev_per_a,
        optimization_device=event.device,
        current_structure=structure_from_positions(
            template,
            event.positions_a,
            name=event.name,
        ),
        stage=event.stage,
        path_energies_ev=list(event.path_energies_ev),
        reactant_endpoint=(
            structure_from_positions(
                template,
                event.reactant_positions_a,
                name="Reactant preoptimized endpoint",
            )
            if event.reactant_positions_a is not None
            else None
        ),
        product_endpoint=(
            structure_from_positions(
                template,
                event.product_positions_a,
                name="Product preoptimized endpoint",
            )
            if event.product_positions_a is not None
            else None
        ),
    )


# Compatibility name used by the legacy DMF adapter.
progress_snapshot = progress_to_schema


def schema_bond_changes(
    reactant: Atoms,
    transition: Atoms,
    product: Atoms,
    expected_coordinates: list[ReactionCoordinate] | None = None,
) -> tuple[list[BondChangeAssessment], bool | None]:
    assessments, consistent = assess_bond_changes(
        reactant,
        transition,
        product,
        expected_coordinates,
    )
    return (
        [
            BondChangeAssessment(
                atom_i=item.atom_i,
                atom_j=item.atom_j,
                kind=item.kind,
                reactant_distance_a=item.reactant_distance_a,
                transition_state_distance_a=item.transition_state_distance_a,
                product_distance_a=item.product_distance_a,
                path_fraction=item.path_fraction,
            )
            for item in assessments
        ],
        consistent,
    )
