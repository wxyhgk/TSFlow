from __future__ import annotations

import json
import math
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

from app.core.config import PROJECT_ROOT
from app.contracts.jobs import Atom, AtomicStructure


MAX_SDF_BYTES = 5 * 1024 * 1024
MAX_SDF_ATOMS = 2_000


class SDFDistanceGeometryError(ValueError):
    pass


def generate_structure_from_2d_sdf_bytes(
    data: bytes,
    filename: str,
    *,
    charge: int,
    spin: int,
) -> AtomicStructure:
    source = Path(filename)
    if source.suffix.lower() != ".sdf":
        raise SDFDistanceGeometryError("input file must use the .sdf extension")
    if len(data) > MAX_SDF_BYTES:
        raise SDFDistanceGeometryError("SDF file exceeds the 5 MB limit")
    if not data:
        raise SDFDistanceGeometryError("SDF file is empty")
    with tempfile.TemporaryDirectory(prefix="uma-sdf-") as directory:
        temporary = Path(directory) / "input.sdf"
        temporary.write_bytes(data)
        structure = generate_structure_from_2d_sdf(
            temporary,
            charge=charge,
            spin=spin,
        )
    return structure.model_copy(
        update={
            "name": source.stem[:255],
            "comment": (
                f"{source.name}; 3D initial conformer generated by deterministic "
                "OpenChemLib distance geometry (seed 0x5eed)"
            ),
        }
    )


def generate_structure_from_2d_sdf(
    path: Path,
    *,
    charge: int,
    spin: int,
) -> AtomicStructure:
    path = path.expanduser().resolve()
    if path.suffix.lower() != ".sdf":
        raise SDFDistanceGeometryError("input file must use the .sdf extension")
    if not path.is_file():
        raise SDFDistanceGeometryError(f"SDF file does not exist: {path}")
    if path.stat().st_size > MAX_SDF_BYTES:
        raise SDFDistanceGeometryError("SDF file exceeds the 5 MB limit")

    node = shutil.which("node")
    if node is None:
        raise SDFDistanceGeometryError("Node.js is required for OpenChemLib distance geometry")
    helper = Path(__file__).resolve().parents[1] / "assets" / "sdf_distance_geometry.mjs"
    openchemlib = _resolve_openchemlib()
    if not helper.is_file():
        raise SDFDistanceGeometryError(f"distance-geometry helper is missing: {helper}")

    completed = subprocess.run(
        [node, str(helper), str(openchemlib), str(path)],
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    if completed.returncode != 0:
        detail = completed.stderr.strip() or "unknown OpenChemLib error"
        raise SDFDistanceGeometryError(detail)
    try:
        payload = json.loads(completed.stdout)
        raw_atoms = payload["atoms"]
    except (json.JSONDecodeError, KeyError, TypeError) as exc:
        raise SDFDistanceGeometryError("OpenChemLib returned invalid conformer data") from exc
    if not isinstance(raw_atoms, list) or not 1 <= len(raw_atoms) <= MAX_SDF_ATOMS:
        raise SDFDistanceGeometryError(
            f"generated atom count must be between 1 and {MAX_SDF_ATOMS}"
        )

    atoms: list[Atom] = []
    for index, item in enumerate(raw_atoms, start=1):
        try:
            symbol = item["symbol"]
            position = tuple(float(value) for value in item["position"])
        except (KeyError, TypeError, ValueError) as exc:
            raise SDFDistanceGeometryError(
                f"generated atom {index} contains invalid data"
            ) from exc
        if len(position) != 3 or not all(math.isfinite(value) for value in position):
            raise SDFDistanceGeometryError(
                f"generated atom {index} contains invalid coordinates"
            )
        atoms.append(Atom(symbol=symbol, position=position))

    return AtomicStructure(
        atoms=atoms,
        charge=charge,
        spin=spin,
        name=path.stem[:255],
        comment=(
            f"{path.name}; 3D initial conformer generated by deterministic "
            "OpenChemLib distance geometry (seed 0x5eed)"
        ),
        source_format="sdf",
    )


def _resolve_openchemlib() -> Path:
    configured = os.environ.get("UMA_OPENCHEMLIB_JS")
    candidates = [
        Path(configured).expanduser() if configured else None,
        PROJECT_ROOT / "frontend" / "node_modules" / "openchemlib" / "dist" / "openchemlib.js",
    ]
    for candidate in candidates:
        if candidate is not None and candidate.is_file():
            return candidate.resolve()
    raise SDFDistanceGeometryError(
        "OpenChemLib is unavailable; run `cd frontend && npm install`, or set "
        "UMA_OPENCHEMLIB_JS to openchemlib.js"
    )
