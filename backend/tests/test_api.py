from uuid import UUID

from fastapi.testclient import TestClient

from app.main import app
from app.schemas.jobs import AtomicStructure, CalculationResult


VALID_OMOL_JOB = {
    "model_name": "uma-s-1p2p1",
    "task_name": "omol",
    "calculation": "single_point",
    "structure": {
        "atoms": [
            {"symbol": "O", "position": [0.0, 0.0, 0.0]},
            {"symbol": "H", "position": [0.76, 0.58, 0.0]},
            {"symbol": "H", "position": [-0.76, 0.58, 0.0]},
        ],
        "charge": 0,
        "spin": 1,
    },
}


def test_health_and_model_inventory() -> None:
    with TestClient(app) as client:
        health = client.get("/api/v1/health")
        assert health.status_code == 200
        assert health.json()["status"] == "ok"
        assert health.json()["checkpoints_available"] == 5

        models = client.get("/api/v1/models")
        assert models.status_code == 200
        assert len(models.json()["items"]) == 5
        assert models.json()["items"][0]["recommended"] is True


def test_job_lifecycle() -> None:
    with TestClient(app) as client:
        created = client.post("/api/v1/jobs", json=VALID_OMOL_JOB)
        assert created.status_code == 202
        assert created.json()["status"] == "queued"
        assert created.headers["location"].endswith(created.json()["id"])

        job_id = created.json()["id"]
        fetched = client.get(f"/api/v1/jobs/{job_id}")
        assert fetched.status_code == 200

        cancelled = client.delete(f"/api/v1/jobs/{job_id}")
        assert cancelled.status_code == 200
        assert cancelled.json()["status"] == "cancelled"


def test_job_summary_list_uses_compact_result_contract() -> None:
    with TestClient(app) as client:
        created = client.post("/api/v1/jobs", json=VALID_OMOL_JOB).json()
        job_id = UUID(created["id"])
        repository = client.app.state.job_repository
        client.portal.call(repository.start, job_id)
        result = CalculationResult(
            energy_ev=-1.25,
            forces_ev_per_a=[(0.0, 0.0, 0.0)] * 3,
            max_force_ev_per_a=0.0,
            final_structure=AtomicStructure.model_validate(
                created["request"]["structure"]
            ),
            converged=True,
            elapsed_seconds=1.0,
        )
        client.portal.call(repository.succeed, job_id, result)
        response = client.get("/api/v1/jobs/summaries")

    assert response.status_code == 200
    item = next(item for item in response.json()["items"] if item["id"] == str(job_id))
    assert item["result_summary"]["kind"] == "calculation"
    assert item["result_summary"]["energy_ev"] == -1.25
    assert "result" not in item


